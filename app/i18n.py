def normalize_language(value: str | None) -> str:
    code = (value or "").strip().lower()
    if code.startswith("zh"):
        return "zh"
    if code.startswith("en"):
        return "en"
    return ""


def detect_language(request: Request, default: str | None = None) -> str:
    cookie = normalize_language(request.cookies.get(LANGUAGE_COOKIE))
    if cookie:
        return cookie
    configured = normalize_language(default) if default else ""
    if configured:
        return configured
    header = request.headers.get("accept-language", "")
    candidates: list[tuple[float, int, str]] = []
    for index, part in enumerate(header.split(",")):
        pieces = part.split(";")
        code = normalize_language(pieces[0])
        if not code:
            continue
        quality = 1.0
        for parameter in pieces[1:]:
            parameter = parameter.strip().lower()
            if parameter.startswith("q="):
                try:
                    quality = float(parameter[2:])
                except ValueError:
                    quality = 0.0
        if quality > 0:
            candidates.append((quality, index, code))
    if candidates:
        candidates.sort(key=lambda item: (-item[0], item[1]))
        return candidates[0][2]
    return DEFAULT_LANGUAGE


def translate(language: str, key: str, **values) -> str:
    language = language if language in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE
    table = TRANSLATIONS.get(language, TRANSLATIONS[DEFAULT_LANGUAGE])
    fallback = TRANSLATIONS[DEFAULT_LANGUAGE]
    count = values.get("count")
    if language == "en" and count is not None and count != 1:
        text = table.get(key + "_plural") or table.get(key) or fallback.get(key) or key
    else:
        text = table.get(key) or fallback.get(key) or key
    try:
        return text.format(**values)
    except (KeyError, ValueError):
        return text


def request_language(request: Request) -> str:
    configured = getattr(request.app.state, "default_language", "auto")
    return detect_language(request, configured)


def tr(request: Request, key: str, **values) -> str:
    return translate(request_language(request), key, **values)


