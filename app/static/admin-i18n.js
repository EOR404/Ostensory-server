  function translate(value) {
    var text = (value || "").trim();
    if (!text) return value;
    var translated = map[text];
    if (!translated) {
      for (var i = 0; i < patterns.length; i += 1) {
        if (patterns[i][0].test(text)) {
          translated = text.replace(patterns[i][0], patterns[i][1]);
          break;
        }
      }
    }
    if (!translated || translated === text) return value;
    var leading = value.match(/^\s*/)[0];
    var trailing = value.match(/\s*$/)[0];
    return leading + translated + trailing;
  }

  function translateAttributes(root) {
    Array.prototype.forEach.call(root.querySelectorAll("[placeholder], [aria-label], [title], [data-confirm]"), function (el) {
      ["placeholder", "aria-label", "title", "data-confirm"].forEach(function (name) {
        var value = el.getAttribute(name);
        if (!value) return;
        var translated = translate(value);
        if (translated !== value) el.setAttribute(name, translated);
      });
    });
  }

  function translateTree(root) {
    if (!root) return;
    translateAttributes(root);
    var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode: function (node) {
        var parent = node.parentElement;
        if (!parent || /^(SCRIPT|STYLE|TEXTAREA)$/.test(parent.tagName)) return NodeFilter.FILTER_REJECT;
        return node.nodeValue && node.nodeValue.trim() ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
      }
    });
    var nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach(function (node) {
      var next = translate(node.nodeValue);
      if (next !== node.nodeValue) node.nodeValue = next;
    });
  }

